"""R^ ports versus pinned Goose-suite C++/Rust sources; no Goose executable.

Windows x64: load scripts/devshell.ps1, then run this script. Every sample
includes process startup, construction, traversal, teardown and output.
"""
import argparse
import ctypes
import hashlib
import json
import os
import pathlib
import platform
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
UPSTREAM = "94cc64daeabcae6f072dc1fe2b864acda5a001bc"
SIZES = {"smoke": 6, "small": 15, "medium": 17, "large": 19}


def command(argv, *, cwd=None):
    result = subprocess.run([str(a) for a in argv], cwd=cwd, capture_output=True,
                            text=True, encoding="utf-8", errors="replace", timeout=120)
    if result.returncode:
        raise RuntimeError(f"{argv}\n{result.stdout}{result.stderr}")
    return (result.stdout + result.stderr).strip()


class MemoryCounters(ctypes.Structure):
    _fields_ = [("cb", ctypes.c_ulong), ("PageFaultCount", ctypes.c_ulong)] + [
        (name, ctypes.c_size_t) for name in (
            "PeakWorkingSetSize", "WorkingSetSize", "QuotaPeakPagedPoolUsage",
            "QuotaPagedPoolUsage", "QuotaPeakNonPagedPoolUsage",
            "QuotaNonPagedPoolUsage", "PagefileUsage", "PeakPagefileUsage")]


def measure(exe, timeout):
    # Keep Popen's process handle alive after exit to read its peak working set.
    with open(str(exe) + ".stdout", "wb") as out, open(str(exe) + ".stderr", "wb") as err:
        start = time.perf_counter_ns()
        with subprocess.Popen([str(exe)], stdin=subprocess.DEVNULL, stdout=out, stderr=err) as proc:
            try:
                proc.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
                raise RuntimeError(f"{exe.name} exceeded {timeout}s")
            milliseconds = (time.perf_counter_ns() - start) / 1e6
            counters = MemoryCounters()
            counters.cb = ctypes.sizeof(counters)
            psapi = ctypes.WinDLL("psapi", use_last_error=True)
            query = psapi.GetProcessMemoryInfo
            query.argtypes = [ctypes.c_void_p, ctypes.POINTER(MemoryCounters), ctypes.c_ulong]
            query.restype = ctypes.c_int
            if not query(int(proc._handle), ctypes.byref(counters), counters.cb):
                raise ctypes.WinError(ctypes.get_last_error())
            code = proc.returncode
    output = pathlib.Path(str(exe) + ".stdout").read_text().strip()
    error = pathlib.Path(str(exe) + ".stderr").read_text().strip()
    if code:
        raise RuntimeError(f"{exe.name} exit {code}: {error}")
    return dict(ms=milliseconds, peak_bytes=counters.PeakWorkingSetSize, output=output)


def oracle(depth):
    lines = [2 ** (depth + 2) - 1]
    for d in range(4, depth + 1, 2):
        iters = 2 ** (depth - d + 4)
        lines.extend((iters, d, iters * (2 ** (d + 1) - 1)))
    lines.append(2 ** (depth + 1) - 1)
    return "\n".join(map(str, lines))


def sized(source, target, depth):
    text = source.read_text(encoding="utf-8")
    lines = text.splitlines()
    hits = 0
    for i, line in enumerate(lines):
        if "BENCH_N" in line:
            lines[i], count = re.subn(r"(?<==)\s*\d+", f" {depth}", line, count=1)
            hits += count
    if hits != 1:
        raise RuntimeError(f"expected one BENCH_N assignment in {source}")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_results(data, out):
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    meta = data["environment"]
    rows = data["rows"]
    lines = ["# R^ benchmark results", "", "Generated by `bench/run_bench.py`.", "",
             f"Measured: {data['started_utc']} (UTC).", "",
             "These are local measurements; no published Goose timings are reused.", "",
             "## Environment", "", "| Item | Value |", "|---|---|"]
    for key in ("cpu", "os", "rhat_commit", "rhat_dirty", "clang", "msvc", "rustc"):
        value = str(meta[key]).replace('|', '/').replace('\n', '; ')
        lines.append(f"| {key} | {value} |")
    lines += [f"| upstream sources | `{UPSTREAM}` |", "",
              f"Two warm-ups; best of {data['reps']} timed runs. Peak memory is the maximum",
              "working set of the timed runs. Samples include the full process lifecycle.", "",
              "R^ uses textual LLVM IR + Clang `-O2`; C++ uses MSVC `/O2 /std:c++20`",
              "and clang-cl `/O2 /std:c++20`; Rust uses `-O -C codegen-units=1`.", "",
              "## bintrees", "",
              "All warm-ups and timed samples match the independent checksum oracle.", ""]
    measured_sizes = sorted({r["size"] for r in rows}, key=lambda s: SIZES[s])
    if measured_sizes:
        largest = measured_sizes[-1]
        columns = [f"{s} (depth={SIZES[s]}) ms" for s in measured_sizes]
        lines.append("| Implementation | " + " | ".join(columns) + f" | {largest} peak MiB |")
        lines.append("|---|" + "---:|" * (len(columns) + 1))
        for label in dict.fromkeys(r["label"] for r in rows):
            group = {r["size"]: r for r in rows if r["label"] == label}
            cells = [f"{group[s]['best_ms']:.2f}" if s in group else "pending" for s in measured_sizes]
            peak = f"{group[largest]['peak_bytes']/1048576:.2f}" if largest in group else "pending"
            lines.append(f"| {label} | " + " | ".join(cells) + f" | {peak} |")
    lines += ["", "## Ratios", "",
              "Comparison time / R^ time: above 1 means R^ is faster. This is one",
              "benchmark, so no suite-wide geometric mean is reported. Memory ratio is",
              "comparison peak / R^ peak; above 1 means R^ uses less resident memory.", "",
              "| Size | Comparison | Speed ratio | Memory ratio |", "|---|---|---:|---:|"]
    for row in rows:
        if row["language"] == "rhat":
            continue
        base = next((r for r in rows if r["language"] == "rhat" and r["size"] == row["size"]), None)
        if base:
            lines.append(f"| {row['size']} | {row['label']} | {row['best_ms']/base['best_ms']:.4f}x | "
                         f"{row['peak_bytes']/base['peak_bytes']:.3f}x |")
    lines += ["", "## Startup floor", "",
              "Empty-program best of five runs (included in the benchmark times above):", "",
              "| Implementation | Best ms | Peak MiB |", "|---|---:|---:|"]
    for row in data["startup"]:
        lines.append(f"| {row['label']} | {row['best_ms']:.2f} | {row['peak_bytes']/1048576:.2f} |")
    lines += ["", "## Limits", "",
              "The R^ port uses two i32 child indices per node (8 bytes), rather than",
              "Goose relative references. It reserves/releases a 64 MiB virtual region for",
              "each tree; the C++/Rust arena rows reuse their scratch allocation across trees.",
              "R^ retains its current runtime bounds checks and per-push Windows memory",
              "commit calls. No runtime or compiler optimizations were introduced for this run.",
              "There is no R^/MSVC row: MSVC does not consume LLVM IR.",
              "Other 15 benchmarks are pending; see [coverage.md](coverage.md).",
              "Raw samples, checksums, source hashes and build commands are in `results.json`.", ""]
    (out / "results.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", type=pathlib.Path, default=ROOT / "build/Release/rhat.exe")
    parser.add_argument("--sizes", nargs="+", choices=SIZES, default=["small", "medium", "large"])
    parser.add_argument("--reps", type=int, default=3)
    parser.add_argument("--timeout", type=int, default=1800)
    parser.add_argument("--out", type=pathlib.Path, default=HERE)
    parser.add_argument("--report-only", action="store_true", help="regenerate Markdown from saved JSON")
    parser.add_argument("--work", type=pathlib.Path, default=ROOT / "build/bench")
    args = parser.parse_args()
    if args.report_only:
        data = json.loads((args.out / "results.json").read_text(encoding="utf-8"))
        write_results(data, args.out)
        return
    if os.name != "nt":
        parser.error("this harness currently measures Windows peak working sets only")
    if args.reps < 1 or args.timeout < 1:
        parser.error("--reps and --timeout must be positive")
    args.compiler = args.compiler.resolve()
    args.work = args.work.resolve()
    args.work.mkdir(parents=True, exist_ok=True)
    clang = os.environ.get("RHAT_CLANG") or shutil.which("clang")
    tools = dict(clang=clang, msvc=shutil.which("cl"), clangcl=shutil.which("clang-cl"), rustc=shutil.which("rustc"))
    if not args.compiler.is_file() or not all(tools.values()):
        parser.error("build R^ Release and load scripts/devshell.ps1; Clang, MSVC and rustc are required")
    import winreg
    with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                        r"HARDWARE\DESCRIPTION\System\CentralProcessor\0") as key:
        cpu = winreg.QueryValueEx(key, "ProcessorNameString")[0].strip()
    msvc_banner = command([tools["msvc"], "/Bv", "/?"])
    msvc_version = next((line.strip() for line in msvc_banner.splitlines()
                         if "Compiler Version" in line or "コンパイラ バージョン" in line), None)
    if not msvc_version:
        raise RuntimeError("could not identify MSVC version in cl /Bv /? output")
    env = dict(cpu=cpu, os=platform.platform(),
               rhat_commit=command(["git", "rev-parse", "HEAD"], cwd=ROOT),
               rhat_dirty=command(["git", "status", "--porcelain"], cwd=ROOT),
               clang=command([clang, "--version"]).splitlines()[0],
               msvc=msvc_version,
               rustc=command([tools["rustc"], "--version"]),
               compiler_sha256=sha(args.compiler), runtime_sha256=sha(ROOT / "runtime/rhat_runtime.c"))
    data = dict(started_utc=datetime.now(timezone.utc).isoformat(), upstream_commit=UPSTREAM,
                reps=args.reps, warmups=2, environment=env, source_hashes={}, rows=[], startup=[], builds=[])
    for path in sorted(HERE.rglob("*")):
        if path.is_file() and path.suffix in (".rh", ".cpp", ".h", ".rs", ".py"):
            data["source_hashes"][str(path.relative_to(ROOT))] = sha(path)

    def build(argv):
        data["builds"].append([str(a) for a in argv])
        command(argv, cwd=args.work)

    def sample(exe, expected):
        result = measure(exe, args.timeout)
        if result["output"] != expected:
            raise RuntimeError(f"checksum mismatch: {exe}\n{result['output']}\nexpected:\n{expected}")
        return result

    def cpp_build(source, exe, tc, defines=()):
        build([tools[tc], "/nologo", "/O2", "/EHsc", "/std:c++20", *defines,
               source, "/Fe" + str(exe), "/Fo" + str(exe.with_suffix(".obj"))])

    # Actual empty-program costs from each code-generation path.
    for label, tc in (("R^ LLVM/Clang", "rhat"), ("C++ MSVC", "msvc"),
                      ("C++ clang-cl", "clangcl"), ("Rust", "rustc")):
        exe = args.work / f"empty_{tc}.exe"
        ext = dict(rhat="rh", msvc="cpp", clangcl="cpp", rustc="rs")[tc]
        src = exe.with_suffix("." + ext)
        src.write_text("" if tc == "rhat" else "fn main() {}" if tc == "rustc" else "int main() {}")
        if tc == "rhat":
            build([args.compiler, "build", src, "-o", exe, "-O2", "--clang", clang])
        elif tc == "rustc":
            build([tools[tc], "-O", "-C", "codegen-units=1", src, "-o", exe])
        else:
            cpp_build(src, exe, tc)
        samples = [sample(exe, "") for _ in range(5)]
        data["startup"].append(dict(label=label, best_ms=min(s["ms"] for s in samples),
                                    peak_bytes=max(s["peak_bytes"] for s in samples), samples=samples))

    for size in args.sizes:
        depth = SIZES[size]
        implementations = []
        src = args.work / f"bintrees_{size}.rh"
        sized(HERE / "rhat/bintrees.rh", src, depth)
        exe = src.with_suffix(".exe")
        build([args.compiler, "build", src, "-o", exe, "-O2", "--clang", clang,
               "--dump-ir", src.with_suffix(".rir")])
        implementations.append(("R^ i32-index local region (LLVM/Clang)", "rhat", exe))
        for tc in ("msvc", "clangcl"):
            for variant, shape in ((0, "new/delete"), (1, "reused arena")):
                exe = args.work / f"bintrees_{size}_{tc}_{variant}.exe"
                cpp_build(HERE / "upstream/cpp/bintrees.cpp", exe, tc,
                          [f"/DBENCH_N={depth}", f"/DVARIANT={variant}"])
                implementations.append((f"C++ {shape} ({tc})", "cpp", exe))
        shutil.copyfile(HERE / "upstream/rust/bench.rs", args.work / "bench.rs")
        for shape in ("box", "arena"):
            src = args.work / f"bintrees_{size}_{shape}.rs"
            sized(HERE / f"upstream/rust/bintrees_{shape}.rs", src, depth)
            exe = src.with_suffix(".exe")
            build([tools["rustc"], "-O", "-C", "codegen-units=1", src, "-o", exe])
            implementations.append((f"Rust {shape}", "rust", exe))
        # Sequential, alternating implementation order between rounds. No concurrent workloads.
        samples = {label: [] for label, _, _ in implementations}
        warmups = {label: [] for label, _, _ in implementations}
        for iteration in range(2 + args.reps):
            ordered = implementations if iteration % 2 == 0 else list(reversed(implementations))
            for label, _, exe in ordered:
                print(f"{size} {label} {'warmup' if iteration < 2 else 'sample'} {iteration+1}", flush=True)
                result = sample(exe, oracle(depth))
                (warmups if iteration < 2 else samples)[label].append(result)
                print(f"  {result['ms']:.2f} ms, {result['peak_bytes']/1048576:.2f} MiB; verified", flush=True)
        for label, language, _ in implementations:
            values = samples[label]
            data["rows"].append(dict(label=label, language=language, size=size, depth=depth,
                                     best_ms=min(s["ms"] for s in values),
                                     peak_bytes=max(s["peak_bytes"] for s in values),
                                     samples=values, warmups=warmups[label]))
        write_results(data, args.out)
    print(f"Wrote {args.out / 'results.md'}", flush=True)


if __name__ == "__main__":
    main()
